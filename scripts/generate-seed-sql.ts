/**
 * Generates supabase/seed.sql from the TypeScript seed content.
 *   npm run db:seed-sql
 * Then: `supabase db reset` (local) or run seed.sql in the SQL editor (hosted).
 * Uses the same table mapping as the CMS publish endpoint (src/admin/tableRows.ts).
 */
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { getSeedContent } from '../src/content/index';
import { validateBundle } from '../src/content/schema';
import { bundleToTableRows } from '../src/admin/tableRows';

const bundle = getSeedContent();
const errors = validateBundle(bundle).filter((i) => i.severity === 'error');
if (errors.length) {
  console.error('Content has errors; fix before seeding:', errors.slice(0, 10));
  process.exit(1);
}

// Postgres array columns (everything else that is an array/object goes to jsonb).
const ARRAY_TYPES: Record<string, string> = {
  age_bands: 'age_band[]', items_by_difficulty: 'int[]',
  tags: 'text[]', confusable_with: 'text[]', variants: 'text[]', syllables: 'text[]', phoneme_focus: 'text[]', concept_ids: 'text[]',
  accepted_variants: 'text[]', skills: 'text[]', phrase_ids: 'text[]', grammar_pattern_ids: 'text[]', prerequisites: 'text[]', traits: 'text[]',
  palette: 'text[]', topics: 'text[]', ambient: 'text[]', world_ids: 'text[]', reward_ids: 'text[]', evidence: 'text[]', hints: 'text[]', environments: 'text[]',
  stages: 'smallint[]', unit_ids: 'text[]', arc_ids: 'text[]', game_types: 'text[]', navigation: 'text[]',
};

const lit = (v: unknown, col: string): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v) && ARRAY_TYPES[col]) {
    const type = ARRAY_TYPES[col];
    return `array[${v.map((x) => (typeof x === 'number' ? String(x) : `'${String(x).replace(/'/g, "''")}'`)).join(',')}]::${type}`;
  }
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out: string[] = ['-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.', 'begin;'];
for (const { table, rows } of bundleToTableRows(bundle)) {
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]!);
  for (let i = 0; i < rows.length; i += 200) {
    const chunk = rows.slice(i, i + 200);
    out.push(`insert into ${table} (${cols.join(', ')}) values\n${chunk.map((r) => `  (${cols.map((c) => lit(r[c], c)).join(', ')})`).join(',\n')}\non conflict do nothing;`);
  }
}

const flags: [string, string, boolean, number, string[]][] = [
  ['newMiniGame', 'Show experimental mini-games in Play mode', false, 0, ['development']],
  ['newStoryEngine', 'Alternative story pacing', false, 0, ['development']],
  ['AIStoryVariation', 'LingoAI picks narrative variations (curriculum unchanged)', false, 0, ['development', 'staging']],
  ['advancedPronunciation', 'Server-side phoneme scoring provider', false, 0, ['development']],
  ['creationMode', 'Create mode', true, 100, ['development', 'staging', 'production']],
  ['experimentalWorld', 'Unreleased world preview', false, 0, ['development']],
];
out.push(`insert into feature_flags (key, description, enabled, rollout_percent, environments) values\n${flags.map(([k, d, e, p, envs]) => `  (${lit(k, '')}, ${lit(d, '')}, ${e}, ${p}, ${lit(envs, 'environments')})`).join(',\n')}\non conflict do nothing;`);
out.push(`insert into experiments (key, description, variants, surface, active) values
  ('reward_reveal_style', 'Sticker reveal animation: burst vs. gentle float', '[{"id":"burst","weight":50},{"id":"float","weight":50}]'::jsonb, 'reward-presentation', false),
  ('story_first_vs_game_first', 'Open journeys with a story beat or a warm-up game', '[{"id":"story","weight":50},{"id":"game","weight":50}]'::jsonb, 'journey-ordering', false)
on conflict do nothing;`);

const json = JSON.stringify(bundle);
const checksum = createHash('sha256').update(json).digest('hex');
out.push(`insert into content_bundles (version, bundle, checksum, published, published_at, notes) values (${lit(bundle.version, '')}, '${json.replace(/'/g, "''")}'::jsonb, '${checksum}', true, now(), 'Seed release') on conflict (version) do nothing;`);
out.push('commit;');
writeFileSync('supabase/seed.sql', out.join('\n\n') + '\n');
console.log(`Wrote supabase/seed.sql (${(out.join('').length / 1024).toFixed(0)} KB, bundle ${bundle.version}, checksum ${checksum.slice(0, 12)}…)`);
